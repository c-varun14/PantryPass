#!/usr/bin/env bash
# Static hosting: private S3 bucket behind CloudFront (origin access control),
# generates web/config.js from .env.generated, syncs web/, and sets CORS on the HTTP API.
# Idempotent: safe to re-run after every UI change to redeploy.
set -euo pipefail
cd "$(dirname "$0")/.."
source infra/00_env.sh
OUT=infra/.env.generated
: "${API_ID:?run infra/60_api.sh first}"
: "${API_URL:?run infra/60_api.sh first}"
: "${COGNITO_CLIENT_ID:?run infra/20_cognito.sh first}"
: "${DONOR_SUB:?run infra/20_cognito.sh first}"
: "${RECEIVER_SUB:?run infra/20_cognito.sh first}"
: "${COORDINATOR_SUB:?re-run infra/20_cognito.sh to create the coordinator}"

upsert_env() {
  local key=$1 val=$2
  grep -v "^export ${key}=" "$OUT" > "$OUT.tmp" 2>/dev/null || true
  { cat "$OUT.tmp"; echo "export ${key}=${val}"; } > "$OUT"
  rm -f "$OUT.tmp"
}

BUCKET=${PREFIX}-web-${ACCOUNT_ID}
OAC_NAME=${PREFIX}-web-oac
DIST_COMMENT=${PREFIX}-web

# ---- 1. private bucket ----
if aws s3api head-bucket --bucket "$BUCKET" 2>/dev/null; then
  echo "bucket exists $BUCKET"
else
  aws s3api create-bucket --bucket "$BUCKET" --region "$REGION" \
    --create-bucket-configuration LocationConstraint="$REGION" >/dev/null
  echo "created bucket $BUCKET"
fi
aws s3api put-public-access-block --bucket "$BUCKET" --public-access-block-configuration \
  BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true
aws s3api put-bucket-tagging --bucket "$BUCKET" --tagging "TagSet=[{Key=$TAG_KEY,Value=$TAG_VALUE}]"

# ---- 2. origin access control ----
OAC_ID=$(aws cloudfront list-origin-access-controls \
  --query "OriginAccessControlList.Items[?Name=='$OAC_NAME'].Id | [0]" --output text)
if [ "$OAC_ID" = "None" ] || [ -z "$OAC_ID" ]; then
  OAC_ID=$(aws cloudfront create-origin-access-control --origin-access-control-config \
    "Name=$OAC_NAME,Description=PantryPass web,SigningProtocol=sigv4,SigningBehavior=always,OriginAccessControlOriginType=s3" \
    --query OriginAccessControl.Id --output text)
  echo "created OAC $OAC_ID"
else
  echo "OAC exists $OAC_ID"
fi

# ---- 3. distribution ----
DIST_ID=$(aws cloudfront list-distributions \
  --query "DistributionList.Items[?Comment=='$DIST_COMMENT'].Id | [0]" --output text)
if [ "$DIST_ID" = "None" ] || [ -z "$DIST_ID" ]; then
  mkdir -p .build
  cat > .build/distribution.json <<JSON
{
  "CallerReference": "${PREFIX}-web-$(date +%s)",
  "Comment": "$DIST_COMMENT",
  "Enabled": true,
  "DefaultRootObject": "index.html",
  "PriceClass": "PriceClass_All",
  "HttpVersion": "http2and3",
  "Origins": { "Quantity": 1, "Items": [ {
    "Id": "s3-web",
    "DomainName": "$BUCKET.s3.$REGION.amazonaws.com",
    "OriginAccessControlId": "$OAC_ID",
    "S3OriginConfig": { "OriginAccessIdentity": "" }
  } ] },
  "DefaultCacheBehavior": {
    "TargetOriginId": "s3-web",
    "ViewerProtocolPolicy": "redirect-to-https",
    "Compress": true,
    "AllowedMethods": { "Quantity": 2, "Items": ["GET", "HEAD"] },
    "CachePolicyId": "4135ea2d-6df8-44a3-9df3-4b5a84be39ad"
  }
}
JSON
  DIST_ID=$(aws cloudfront create-distribution-with-tags --distribution-config-with-tags \
    "{\"DistributionConfig\": $(cat .build/distribution.json), \"Tags\": {\"Items\": [{\"Key\": \"$TAG_KEY\", \"Value\": \"$TAG_VALUE\"}]}}" \
    --query Distribution.Id --output text)
  echo "created distribution $DIST_ID"
else
  echo "distribution exists $DIST_ID"
fi
CF_DOMAIN=$(aws cloudfront get-distribution --id "$DIST_ID" --query Distribution.DomainName --output text)
DIST_ARN="arn:aws:cloudfront::$ACCOUNT_ID:distribution/$DIST_ID"

# ---- 4. bucket policy: only this distribution may read ----
aws s3api put-bucket-policy --bucket "$BUCKET" --policy "{
  \"Version\": \"2012-10-17\",
  \"Statement\": [{
    \"Sid\": \"AllowCloudFrontRead\",
    \"Effect\": \"Allow\",
    \"Principal\": {\"Service\": \"cloudfront.amazonaws.com\"},
    \"Action\": \"s3:GetObject\",
    \"Resource\": \"arn:aws:s3:::$BUCKET/*\",
    \"Condition\": {\"StringEquals\": {\"AWS:SourceArn\": \"$DIST_ARN\"}}
  }]
}"

# ---- 5. CORS on the HTTP API ----
aws apigatewayv2 update-api --api-id "$API_ID" --cors-configuration \
  "AllowOrigins=https://$CF_DOMAIN,http://localhost:8080,http://localhost:8099,AllowMethods=GET,POST,OPTIONS,AllowHeaders=authorization,content-type,MaxAge=3600" >/dev/null
echo "CORS set for https://$CF_DOMAIN"

# ---- 6. config.js (public identifiers only, no secrets) ----
cat > web/config.js <<JS
// Generated by infra/70_hosting.sh. Do not edit. Nothing secret is stored here.
window.PP_CONFIG = {
  apiUrl: "$API_URL",
  region: "$REGION",
  clientId: "$COGNITO_CLIENT_ID",
  people: [
    { name: "Asha (donor)", username: "donor1", role: "donor", sub: "$DONOR_SUB" },
    { name: "Ravi (receiver)", username: "receiver1", role: "receiver", sub: "$RECEIVER_SUB" },
    { name: "Meera (coordinator)", username: "coordinator1", role: "coordinator", sub: "$COORDINATOR_SUB" }
  ]
};
JS

# ---- 7. upload and invalidate ----
aws s3 sync web/ "s3://$BUCKET/" --delete --exclude "config.example.js" \
  --cache-control "no-cache" >/dev/null
aws cloudfront create-invalidation --distribution-id "$DIST_ID" --paths '/*' >/dev/null

upsert_env WEB_BUCKET "$BUCKET"
upsert_env CLOUDFRONT_ID "$DIST_ID"
upsert_env CLOUDFRONT_DOMAIN "$CF_DOMAIN"
echo "site ready: https://$CF_DOMAIN (first deploy can take a few minutes to propagate)"
